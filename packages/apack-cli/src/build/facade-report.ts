// The reviewed report of a pack's facade types (`etc/pack-types.api.md`): its text, and what the committed
// one says about a facade.
//
// Two callers, which is why the text lives here rather than in the command that records it: `apack
// facade-report` derives the facade from the pack's sources and compares, and `apack pack build` compares the
// bundle it has just produced. One module is what keeps them from normalising or wording the same report
// differently — and the label the normalisation parses under is computed here rather than passed, so the
// command's temp path and the build's `dist` path cannot reach the output between them.
//
// Writing stays out: only `facade-report --update` writes the report, and the build never does.
import * as fs from 'node:fs';
import * as path from 'node:path';
import { PACK_TYPES_FACADE } from '@apackdev/sdk/build';
import { PACK_LAYOUT, readPackBuild } from '@apackdev/host/packs';
import { readPackBuildInputs, assertPackBuildInputsCurrent } from '@apackdev/host/build/pack-build-inputs';
import ts from 'typescript';
import { sortLiteralUnions } from './declaration-text';

/** The pack's committed facade report, the file `facade:check` holds a facade to */
export function facadeReportFile(packDir: string): string {
  return path.join(packDir, 'etc', `${PACK_TYPES_FACADE}.api.md`);
}

/** A path relative to where the command was run, for a message someone reads in a terminal */
export function shownPath(file: string): string {
  return path.relative(process.cwd(), file) || '.';
}

/**
 * The label the bundle is parsed under. The canonical path of what `apack pack build` writes, whoever produced
 * the text: a declaration bundle's own filename decides nothing about the report, and deriving it here is
 * what makes that true by construction rather than by two callers agreeing.
 */
function bundleLabel(packDir: string): string {
  return path.join(packDir, 'dist', PACK_LAYOUT.typesDir, `${PACK_TYPES_FACADE}.d.ts`);
}

/** Reuse the facade dependents read only after verifying sealed output and current recorded inputs. */
export function readBuiltFacadeReport(packDir: string): string {
  const directory = path.join(packDir, 'dist');
  const { snapshot, integrity } = readPackBuild(directory);
  assertPackBuildInputsCurrent(packDir, readPackBuildInputs(directory, integrity));
  const facade = snapshot.facades[PACK_TYPES_FACADE];
  if (typeof facade !== 'string' || !facade.trim()) throw new Error('Built pack has no pack-types facade; rebuild the complete pack');
  return facadeReportText(facade, packDir, snapshot.manifest.id);
}

/** Names a top-level statement declares, its sort key */
function declaredName(statement: ts.Statement): string {
  if (ts.isVariableStatement(statement)) return statement.declarationList.declarations.map((d) => d.name.getText()).join(',');
  const name = (statement as { name?: ts.Node }).name;
  return name ? name.getText() : '';
}

/** Import names in sorted order: `import { b, a } from 'x'` → `import { a, b } from 'x'` */
function sortImportNames(text: string): string {
  return text.replace(/\{([^}]*)\}/, (_, names: string) => `{ ${names.split(',').map((n) => n.trim()).filter(Boolean).sort().join(', ')} }`);
}

/**
 * The report a facade bundle normalises to: imports first and sorted, declarations in name order, literal
 * unions sorted, the pack's own path shortened. The point is that it moves only when the facade does —
 * TypeScript emits a bundle whose statement and import order are its own business, so a report taken from
 * one verbatim would differ from itself.
 */
export function facadeReportText(built: string, packDir: string, packId: string): string {
  const label = bundleLabel(packDir);
  const bundle = sortLiteralUnions(built, label);
  const file = ts.createSourceFile(label, bundle, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const chunks = file.statements.map((statement, index) => {
    const text = bundle.slice(statement.getFullStart(), statement.end).trim();
    // Imports, then declarations, then the export list
    const group = ts.isImportDeclaration(statement) ? 0 : ts.isExportDeclaration(statement) && !statement.moduleSpecifier ? 2 : 1;
    const key = ts.isImportDeclaration(statement) ? (statement.moduleSpecifier as ts.StringLiteral).text : declaredName(statement);
    return { group, key, index, text: group === 0 ? sortImportNames(text) : text };
  });
  // Same-name declarations (overloads, merged interfaces) keep their bundle order
  chunks.sort((a, b) => a.group - b.group || (a.key < b.key ? -1 : a.key > b.key ? 1 : a.index - b.index));
  const body = chunks.map((c, i) => `${i > 0 ? (c.group === 0 ? '\n' : '\n\n') : ''}${c.text}`).join('').replaceAll(packDir, '.');
  return [
    `## Facade types report for the "${packId}" pack`,
    '',
    '> Do not edit this file. It is the pack\'s facade types — what packs depending on this one compile against —'
      + ' re-derived from `src/` every time it is checked. Regenerate with `npm run facade:update`.',
    '',
    '```ts',
    body,
    '```',
    '',
  ].join('\n');
}

/** What the committed report says about a facade: it matches, there is none, or it has gone stale */
export interface FacadeReportComparison {
  readonly state: 'current' | 'missing' | 'stale';
  /** The problem and its fix, for a caller to print. Absent only when the state is `current`. */
  readonly problem?: string;
}

/** Apply the emitter's union rules and compare uniquely named inferred properties independent of order. */
function comparableReport(report: string): string {
  return report.replace(/```ts\n([\s\S]*?)\n```/, (_block, declarations: string) => {
    const file = ts.createSourceFile('facade.d.ts', sortLiteralUnions(declarations, 'facade.d.ts'), ts.ScriptTarget.Latest, true);
    const result = ts.transform(file, [context => {
      const visit: ts.Visitor = node => {
        const visited = ts.visitEachChild(node, visit, context);
        if (!ts.isTypeLiteralNode(visited) || !visited.members.every(ts.isPropertySignature)) return visited;
        const members = [...visited.members];
        const names = members.map(member => member.name.getText(file));
        // Duplicate names and overloads can have order-dependent meaning: leave them alone.
        if (new Set(names).size !== names.length) return visited;
        members.sort((a, b) => a.name.getText(file).localeCompare(b.name.getText(file)));
        return ts.factory.updateTypeLiteralNode(visited, ts.factory.createNodeArray(members));
      };
      return node => ts.visitNode(node, visit) as ts.SourceFile;
    }]);
    try {
      return '```ts\n' + ts.createPrinter().printFile(result.transformed[0]) + '```';
    } finally {
      result.dispose();
    }
  });
}

/**
 * The committed report against the facade `next` describes. Three states rather than a boolean, because
 * "there is no report" and "the report is wrong" are different answers and only one of them is a diff.
 */
export function compareFacadeReport(packDir: string, next: string): FacadeReportComparison {
  const reportFile = facadeReportFile(packDir);
  const current = fs.existsSync(reportFile) ? fs.readFileSync(reportFile, 'utf-8') : undefined;
  if (current === next || (current !== undefined && comparableReport(current) === comparableReport(next))) return { state: 'current' };
  const fix = 'If the facade change is intended, run npm run facade:update and commit the report.';
  return current === undefined
    ? { state: 'missing', problem: `${shownPath(reportFile)} doesn't exist. ${fix}` }
    : { state: 'stale', problem: `${shownPath(reportFile)} differs from the pack's facade types. ${fix}` };
}

/** The `onFile` rows flattened for `it.each`, which wants one row per case rather than one per rule */
const FIRES_ON_A_FILE: [PackRuleKey, string, string][] = Object.entries(FIRES)
  .flatMap(([key, cases]) => (cases.onFile ?? []).map(([code, problem]): [PackRuleKey, string, string] =>
    [key as PackRuleKey, code, problem]));

/**
 * One firing example per rule, so none of them can land without a case that proves it bites — the same
 * property `check:specifiers`' own spec asserts for the repo's rules — and that the rule it bites for is the
 * only one that reports it. The pack fixture carries the
 * `package.json` `imports` map that makes a `#` string a specifier rather than a colour.
 */
describe('every rule', () => {
  /** A pack with an imports map, a generated facade to resolve against, and whatever else the case writes */
  /** A complete pack, in a temp directory this file removes: the shape is `packFixture`'s, the lifetime is ours */
  const completePack = (files: Record<string, string>) => {
    const dir = packFixture({ files });
    dirs.push(dir);
    return dir;
  };

  /**
   * The whole map rather than this rule's row. Asking one key says the rule fired and nothing about whether a
   * second reported the same line — which is what a pack author would then be told twice, and what the dedupe
   * in `packRuleProblems` exists to prevent. Three rules had nothing pinning them as an owner before this read
   * the map: `own-modules`, `pack-own-aliases` and `repository-casts`. The other nine are covered either here
   * or by the hand-written pairs below, whose sites are the shape this cannot reach — a line two rules are both
   * right about, rather than a line written for one of them.
   *
   * It is a regression guard and has no firing case of its own, which is worth knowing before trusting it:
   * measured by disabling the span dedupe in `packRuleProblems`, every row here still passes, because no rule's
   * canonical line is one another rule also claims — which is the thing being asserted. What it catches is a
   * *new* rule whose predicate starts claiming an existing rule's example. The mechanism it uses, reading the
   * whole map rather than one key, is watched failing by the pairs below, which is where a second reporter
   * actually appears.
   */
  it.each(FIRES_ON_A_FILE)('%s fires on an offending file, and owns it', (key, code, problem) => {
    const dir = completePack({ 'src/f.ts': code });
    const reported = [...packRuleProblems(dir)].flatMap(([owner, found]) => found.map((line) => `${owner}: ${line}`));
    expect(reported).toEqual([`${key}: ${problem}`]);
  });

  /**
   * `apack pack generate-entries` writes this very cast into every pack's `#generated/repository`, where it is the
   * point: the registry is untyped and the facade is what types it. It escapes the rule's shape only by naming
   * its import `earsRepository`, which is a rename away from failing every pack's build, so the exemption is by
   * what the file *is*. The offending spelling outside `__generated__` still fires, or the exemption would be
   * the rule.
   */
  it('repository-casts allows the generated facade, which is this cast by design', () => {
    const cast = 'export const repository = repository as unknown as Repositories;\n';
    const dir = completePack({ 'src/__generated__/written-by-codegen.ts': cast, 'src/hand-written.ts': cast });
    expect(problems(dir, 'repository-casts')).toEqual(['src/hand-written.ts:1: repository as unknown as Repositories']);
  });

  /**
   * The acceptance half, which is the half a reservation needs: a key named `_call` is refused, and every
   * neighbouring shape a pack legitimately writes is not — a field of its own whose name merely starts with
   * an underscore, the two verbs that ask about a call without reading it, and the test helper that builds
   * an answer.
   */
  it("reserved-event-keys leaves a pack's own fields and the call verbs alone", () => {
    const dir = completePack({
      'src/writes-it.ts': "export const bad = { type: 'DONE', _call: mine };\n",
      'src/own-field.ts': "export const fine = { type: 'DONE', _callCount: 2, call: 'a-name' };\n",
      'src/asks-it.ts': 'export const mine = (event: E) => answersCall(event, pending);\n',
      'src/settles-it.ts': 'export const settle = (p: P, event: E) => settleCall(p, event);\n',
      'src/in-a-test.ts': "export const answer = answerTo(call, { type: 'DONE' });\n",
    });
    expect(problems(dir, 'reserved-event-keys')).toEqual(['src/writes-it.ts:1: _call:']);
  });

  /**
   * And it reaches a pack's **tests**, which is where the key is reached for at all.
   *
   * A pack's own code has the verbs and no reason to name the key. A spec driving a machine directly has no
   * delivery door in front of it, so it has to synthesise what a door would write — which is `answerTo`'s
   * job, and this is what refuses the hand-rolled alternative. `apack pack test` passes `['tests']` for the
   * same reason, so both entry points cover the same ground.
   */
  it('reserved-event-keys fires in a pack\'s tests as well as its src', () => {
    const dir = completePack({ 'tests/drives-a-machine.spec.ts': "actor.send({ type: 'DONE', _call: mine });\n" });

    expect(packRuleProblems(dir, ['src', 'tests']).get('reserved-event-keys'))
      .toEqual(['tests/drives-a-machine.spec.ts:1: _call:']);
  });

  it('backend-console fires under a backend path and not under a frontend one', () => {
    const dir = completePack({
      'src/features/memos/be/system.ts': "console.log('x');\n",
      'src/features/memos/fe/state.ts': "console.log('x');\n",
    });
    expect(problems(dir, 'backend-console')).toEqual(['src/features/memos/be/system.ts:1: console.log']);
  });

  /**
   * The exclusion is half the rule, so it is half the case.
   *
   * A feature's component has `useSurface()` and so has somewhere else to send; an extension's does not —
   * `#generated/fe` gives it no actor type and `cross-feature-imports` refuses it the feature's own — so
   * `sendToSurface` is the only route it has. Flagging it would leave an author told to do something the
   * pack contract does not let them do.
   */
  it("component-sends flags a feature's component and allows an extension's", () => {
    const send = "import { sendToSurface } from '#generated/events.ts';\nsendToSurface('notes', { type: 'X' });\n";
    const dir = completePack({
      'src/features/memos/fe/panel.vue': `<script setup lang="ts">\n${send}</script>\n`,
      'src/extensions/blocks/display/card.vue': `<script setup lang="ts">\n${send}</script>\n`,
      // A feature's own machine is where the send belongs, and it is not a component
      'src/features/memos/fe/state.ts': send,
    });
    expect(problems(dir, 'component-sends')).toEqual(['src/features/memos/fe/panel.vue:3: sendToSurface(…)']);
  });

  it("cross-feature-imports flags another feature's frontend and allows a feature its own", () => {
    const dir = completePack({
      'package.json': JSON.stringify({ name: 'p', type: 'module', imports: { '#generated/*': './src/__generated__/*', '#features/*': './src/features/*' } }),
      'src/features/code/fe/panel.ts': "import { id } from '#features/actions/fe/state.ts';\nimport { own } from './state.ts';\n",
      'src/features/code/fe/state.ts': 'export const own = 1;\n',
    });
    expect(problems(dir, 'cross-feature-imports')).toEqual(['src/features/code/fe/panel.ts:1: #features/actions/fe/state.ts']);
  });

  /**
   * The exemption is read once per pack and cached, and the cache has to notice a manifest that changed without the
   * clock moving. It is keyed on the manifest's size as well as its mtime for exactly this: APFS timestamps are
   * sub-millisecond, but a 1-second granularity is ordinary elsewhere, and there a rewrite inside one tick reads as
   * unchanged — so the stale answer would return only on a filesystem nobody runs the suite on.
   *
   * `utimesSync` puts the mtime back where it was, which is that filesystem's behaviour on this one.
   */
  it('re-reads a pack whose exports changed while its mtime did not', () => {
    const files = (exported: Record<string, string>) => ({
      'package.json': JSON.stringify({ name: 'p', type: 'module', exports: exported }),
      'src/features/memos/fe/state.ts': 'export const memos = 1;\n',
      'src/extensions/viewer.ts': "import { memos } from '../features/memos/fe/state.ts';\nexport const viewer = memos;\n",
    });
    const dir = pack(files({ './viewer': './src/extensions/viewer.ts' }));

    // Both writes are stamped with one timestamp, so `mtimeMs` is identical across them to the digit the cache
    // reads. Putting a *captured* mtime back does not do it: statSync reports sub-millisecond precision and
    // utimesSync takes a Date, so the restored value differs and the cache misses for the wrong reason — measured,
    // the case passed with the size removed from the key.
    const manifest = path.join(dir, 'package.json');
    const frozen = new Date('2026-01-01T00:00:00.000Z');
    fs.utimesSync(manifest, frozen, frozen);
    // Published from outside every feature, so it is the module that assembles the pack
    expect(problems(dir, 'cross-feature-imports')).toEqual([]);
    fs.writeFileSync(manifest, JSON.stringify({ name: 'p', type: 'module', exports: {} }));
    fs.utimesSync(manifest, frozen, frozen);

    expect(problems(dir, 'cross-feature-imports'),
      'the manifest publishes nothing now, so viewer.ts has no licence — a cache keyed on mtime alone would still say it does')
      .toEqual(['src/extensions/viewer.ts:1: ../features/memos/fe/state.ts']);
  });

  /**
   * A whole-pack rule, so its findings arrive as written with no span. Which module is a contract is what
   * `apack.json` says — and, where a tree has none, what the layout says; the case below is that half.
   */
  it('contract-leaves flags a contract leaf that reaches its own machine', () => {
    const dir = completePack({
      'src/features/memos/fe/contract.ts': "import type { Ctx } from './state.ts';\nexport type Contract = { state: Ctx };\n",
      'src/features/memos/fe/state.ts': "import { sendToSurface } from '#generated/events.ts';\nexport type Ctx = { sent: typeof sendToSurface };\n",
    });
    expect(problems(dir, 'contract-leaves')).toEqual(['src/features/memos/fe/contract.ts:1: ./state.ts']);
  });

  /**
   * And where no manifest names them, `features/<id>/{be,fe}/contract.ts` does.
   *
   * Two trees here have no `apack.json` and never will: the app is the pack `host`, whose features are real
   * code, and the CLI's scaffold builds its manifest in code from computed keys. Both sit in this rule's
   * population on purpose, and while the manifest was the only way in it answered `[]` before reading a byte —
   * so the host's two contracts had never been checked at all. A manifest still wins where there is one, since
   * it can name a contract this layout would miss.
   */
  it('contract-leaves reads the layout when no manifest names the contracts', () => {
    const dir = pack({
      'package.json': JSON.stringify({ name: 'p', type: 'module', imports: { '#generated/*': './src/__generated__/*' } }),
      'src/features/memos/be/contract.ts': "import type { M } from './system.ts';\nexport type Contract = { m: M };\n",
      'src/features/memos/be/system.ts': 'export type M = 1;\n',
    });
    expect(problems(dir, 'contract-leaves')).toEqual(['src/features/memos/be/contract.ts:1: ./system.ts']);
  });

  /**
   * The one shape both a whole-pack rule and a per-file one are right about: a contract leaf importing another
   * feature's frontend is a crossing (`cross-feature-imports`) and a leaf reaching outside its feature
   * (`contract-leaves`). Before the site dedupe, `apack pack validate` printed the identical line under both
   * sentences — one offence, two messages, which is the thing this table is ordered to prevent.
   *
   * `contract-leaves` keeps it, being second in that order where the crossing is last.
   */
  /**
   * The same one-offence-one-message claim where the two rules *word* it differently, which is what the finding's
   * `subject` is for. `own-modules` says "'#generated/events' names no file — write '#generated/events.ts'" and
   * `contract-leaves` says `#generated/events`; keyed on the sentence they look like two offences, and a pack
   * author writing one extensionless import was told about it twice. Keyed on the subject they are one.
   */
  it('reports an offence two rules word differently under one rule, not two', () => {
    const dir = completePack({
      'src/features/memos/fe/contract.ts': "import { sendToSystem } from '#generated/events';\nexport type Contract = { state: {} };\n",
    });
    const reported = [...packRuleProblems(dir)].filter(([, found]) => found.some((line) => line.includes('#generated/events')));
    expect(reported.map(([key]) => key), 'one import, told to a pack author under more than one rule').toEqual(['contract-leaves']);
  });

  it('reports a contract leaf reaching another feature under one rule, not two', () => {
    const dir = completePack({
      'src/features/memos/fe/contract.ts': "import type { T } from '../../calendar/fe/state.ts';\nexport type Contract = { state: { t: T } };\n",
      'src/features/memos/fe/surface.ts': 'export type P = { id: string };\n',
      'src/features/calendar/fe/state.ts': 'export type T = { id: string };\n',
    });
    const offence = 'src/features/memos/fe/contract.ts:1: ../../calendar/fe/state.ts';
    const reported = [...packRuleProblems(dir)].filter(([, found]) => found.includes(offence)).map(([key]) => key);
    expect(reported, 'the same import, word for word, under more than one rule').toEqual(['contract-leaves']);
  });

  /**
   * And the site is the offence, not the line. Two imports on one line are two offences, so a whole-pack rule
   * claiming the first must not take the second with it — which is why the key carries `what`. Dropping it from
   * the key passes every other case in this file, so this is the one that holds it.
   */
  it('claims the offence a whole-pack rule named, not the whole line it sat on', () => {
    const dir = completePack({
      'src/features/memos/fe/contract.ts':
        "import type { T } from '../../calendar/fe/state.ts'; import { untypedSendToSystem } from '@apackdev/sdk/events';\n"
        + 'export type Contract = { state: { t: T; send: typeof untypedSendToSystem } };\n',
      'src/features/memos/fe/surface.ts': 'export type P = { id: string };\n',
      'src/features/calendar/fe/state.ts': 'export type T = { id: string };\n',
    });
    expect(problems(dir, 'contract-leaves')).toEqual(['src/features/memos/fe/contract.ts:1: ../../calendar/fe/state.ts']);
    expect(problems(dir, 'untyped-sends'), 'the second offence on that line went with the first')
      .toEqual(['src/features/memos/fe/contract.ts:1: untypedSendToSystem from @apackdev/sdk/events']);
  });

  it('names a case that exists for each rule covered elsewhere', () => {
    const own = fs.readFileSync(fileURLToPath(import.meta.url), 'utf-8');
    // Either quote style: a title holding an apostrophe is written with double quotes, and a pointer check that
    // only matched single ones would report a case that is right there
    const declared = (title: string) => [`it('`, `it("`, `describe('`, `describe("`]
      .some((open) => own.includes(`${open}${title}${open.at(-1)}`));
    const gone = Object.entries(FIRES)
      .flatMap(([key, cases]) => (cases.elsewhere === undefined ? [] : [[key, cases.elsewhere] as const]))
      .filter(([, title]) => !declared(title))
      .map(([key, title]) => `${key} names "${title}", which is no case in this file`);
    expect(gone, 'a pointer to a case that no longer exists is the claim this table exists to avoid').toEqual([]);
  });
});

/**
 * The opt-out. Switchable means "a violation has no runtime effect", so the list of names a pack may write is
 * derived from the rules rather than repeated, and a name outside it is an error naming what is allowed —
 * a silent typo would leave a rule off for as long as nobody looked.
 */
describe('manifest checks.allow', () => {
  const withChecks = (checks: object) => {
    const dir = pack({ 'apack.json': JSON.stringify({ id: 'example', name: 'Example', version: '1.0.0' }), 'package.json': JSON.stringify({ name: 'p', type: 'module' }), 'src/extensions/steps/x.ts': "console.log('x');\n" });
    const file = path.join(dir, 'apack.json');
    fs.writeFileSync(file, JSON.stringify({ ...JSON.parse(fs.readFileSync(file, 'utf8')), checks }));
    return dir;
  };

  it('silences a switchable rule the pack allows', () => {
    expect([...packRuleProblems(withChecks({ allow: ['backend-console'] }))]).toEqual([]);
  });

  it('reports the rule when the pack allows nothing', () => {
    expect(problems(withChecks({ allow: [] }), 'backend-console')).toEqual(['src/extensions/steps/x.ts:1: console.log']);
  });

  it.each(['host-imports', 'no-console'])('refuses a non-switchable or unknown rule: %s', key => {
    expect(() => packRuleProblems(withChecks({ allow: [key] }))).toThrow('checks.allow.0');
    expect(() => packRuleProblems(withChecks({ allow: [key] }))).toThrow(key);
    expect(() => packRuleProblems(withChecks({ allow: [key] }))).toThrow('backend-console');
  });

  it('refuses a value that is not a list', () => {
    expect(() => packRuleProblems(withChecks({ allow: 'backend-console' }))).toThrow('checks.allow');
  });

  it('is optional: a pack without checks allows nothing', () => {
    expect([...packRuleProblems(pack({ 'src/f.ts': 'export const x = 1;\n' }))]).toEqual([]);
  });
});

/** What `apack pack build` throws: every failing rule at once, and the paste-able line for the switchable ones */
describe('refusePackRuleViolations', () => {
  it('names every rule that fired, and how to allow the switchable one', () => {
    const dir = pack({
      'src/extensions/steps/x.ts': "import { edgeStore } from '@apackdev/host/ears';\nconsole.log('x');\n",
    });
    let message = '';
    try {
      refusePackRuleViolations(dir);
    } catch (err) {
      message = (err as Error).message;
    }
    expect(message).toContain('2 pack rules failed.');
    expect(message).toContain('src/extensions/steps/x.ts:1: @apackdev/host/ears');
    expect(message).toContain('src/extensions/steps/x.ts:2: console.log');
    expect(message).toContain('{ "checks": { "allow": ["backend-console"] } }');
    expect(message, 'a rule that is not switchable must not offer a way to allow it')
      .not.toContain('["host-imports"]');
  });

  it('returns for a pack with nothing to report', () => {
    expect(() => refusePackRuleViolations(pack({ 'src/f.ts': 'export const x = 1;\n' }))).not.toThrow();
  });
});

/**
 * One offence, one message. Several rules can be right about one import, and a pack author deleting one line
 * should be told the thing that matters about it — not the same line three times in three blocks.
 */
describe('when several rules are right about one site', () => {
  // One line per finding rather than a key's findings joined: a separator inside a message would otherwise read
  // as two findings, and the assertion could not tell which it had — the same reason a pack rule's findings are
  // an array and not a formatted blob
  const offender = (code: string) => {
    const dir = pack({ 'package.json': JSON.stringify({ name: 'p', type: 'module' }), 'src/extensions/steps/x.ts': code });
    return [...packRuleProblems(dir)].flatMap(([key, found]) => found.map((problem) => `${key}: ${problem}`));
  };

  it('reports the cause that comes first, and only that one', () => {
    // Three rules are right: @apackdev/host is not installed for a pack, `_rootEvents` is @internal, and it is
    // the raw transport. The import is unusable because the package is absent, so that is what is said about it;
    // `raw-transport` still names the identifier, which is a second thing to change rather than the same one.
    expect(offender("import { _rootEvents } from '@apackdev/host/bus';\n")).toEqual([
      'host-imports: src/extensions/steps/x.ts:1: @apackdev/host/bus',
      'raw-transport: src/extensions/steps/x.ts:1: _rootEvents',
    ]);
  });

  /** The same, at a path the case picks, in a complete pack — for a specifier that has to resolve to fire */
  const offenderIn = (at: string, code: string, extra: Record<string, string> = {}) => {
    const dir = packFixture({ files: { [at]: code, ...extra } });
    dirs.push(dir);
    return [...packRuleProblems(dir)].flatMap(([key, found]) => found.map((problem) => `${key}: ${problem}`));
  };

  it('keeps two real offences that happen to share a line', () => {
    expect(offender("import { edgeStore } from '@apackdev/host/ears'; console.log('x');\n")).toEqual([
      'host-imports: src/extensions/steps/x.ts:1: @apackdev/host/ears',
      'backend-console: src/extensions/steps/x.ts:1: console.log',
    ]);
  });

  /**
   * One specifier two rules are both right about, for each pair whose predicates can hold at once. The matrix in
   * repo-checks puts *one rule's* offending line at each place a rule discriminates on, so it can only find a pair
   * that claims a line written for one of them; these are the other shape, and every one of them was unpinned —
   * a precedence change would have moved what an author is told and nothing would have failed.
   */
  it('gives an @internal send to the rule about @internal names, not the one about sends', () => {
    // `_sendToLocalSurface` is the one EVENT_SENDS member that is also `_`-prefixed
    expect(offender("import { _sendToLocalSurface } from '@apackdev/sdk/events';\n")).toEqual([
      'internal-package-imports: src/extensions/steps/x.ts:1: _sendToLocalSurface from @apackdev/sdk/events',
    ]);
  });

  it('gives an untyped send from the raw transport to the send rule', () => {
    expect(offender("import { untypedSendToSystem } from '@apackdev/sdk/rpc/client';\n")).toEqual([
      'untyped-sends: src/extensions/steps/x.ts:1: untypedSendToSystem from @apackdev/sdk/rpc/client',
    ]);
  });

  /**
   * And the owner changes with the place: `untyped-sends` exempts generated code and `raw-transport` does not, so
   * the same line is one rule's outside `__generated__` and the other's inside it. Both halves were pinned
   * separately — each rule's own early return — and nothing said the site changes hands.
   */
  it('hands that site to the transport rule inside generated code, which exempts nothing', () => {
    expect(offenderIn('src/__generated__/x.ts', "import { untypedSendToSystem } from '@apackdev/sdk/rpc/client';\n"))
      .toEqual(['raw-transport: src/__generated__/x.ts:1: @apackdev/sdk/rpc/client']);
  });

  it('gives an @internal name from the store to the rule about the store', () => {
    expect(offender("import { _x } from '@apackdev/ears/lmdb';\n")).toEqual([
      'elmdb-imports: src/extensions/steps/x.ts:1: @apackdev/ears/lmdb',
    ]);
  });

  it('gives a cast of the raw transport to the transport rule, whose span sits inside the cast', () => {
    expect(offender('const r = (_rootEvents.repository as unknown as Repos);\n')).toEqual([
      'raw-transport: src/extensions/steps/x.ts:1: _rootEvents',
    ]);
  });

  /**
   * The pair the ordering principle is written for. An extensionless cross-feature import is both unresolvable and
   * a crossing, and cause order alone would hand it to `own-modules`: the author adds `.ts`, re-runs, and is then
   * told the import should not exist at all, which is the fix that subsumes the one they just made.
   *
   * So `cross-feature-imports` is ranked above it deliberately, and this is the case that holds it there — the
   * repo's own `check:specifiers` and every fixture pack pass either way, so nothing else would notice a revert.
   */
  it('gives an extensionless cross-feature import to the rule about the crossing, the fix that subsumes the other', () => {
    expect(offenderIn('src/extensions/viewer.ts', "import { t } from '#features/calendar/fe/state';\n",
      { 'src/features/calendar/fe/state.ts': 'export const t = 1;\n' }))
      .toEqual(['cross-feature-imports: src/extensions/viewer.ts:1: #features/calendar/fe/state']);
  });

  /**
   * A whole-pack finding says where it is separately from what it says, and this is why: `source-resolution`
   * reports `@apackdev/sdk -> <where it landed>`, a path *outside* the pack, and `contract-leaves` reports two paths
   * inside it. A consumer that rewrote paths by editing the string would prefix the first — which would be wrong —
   * and would have to know the second's wording to find both.
   */
  it('rewrites the places a whole-pack finding names, and nothing else', () => {
    const where = (file: string) => `packages/demo/${file}`;
    expect(formatPackWide({ what: '@apackdev/sdk -> ../apack-sdk/src/index.ts' }, where))
      .toBe('@apackdev/sdk -> ../apack-sdk/src/index.ts');
    expect(formatPackWide({ what: '@apackdev/source', at: { file: 'vitest.config.ts', line: 1 } }, where))
      .toBe('packages/demo/vitest.config.ts:1: @apackdev/source');
    expect(formatPackWide({ what: './state.ts', at: { file: 'src/a/fe/contract.ts', line: 2 }, from: 'src/a/be/contract.ts' }, where))
      .toBe('packages/demo/src/a/fe/contract.ts:2: ./state.ts (reached from packages/demo/src/a/be/contract.ts)');
    // The default writes them as the rule did, which is what `apack pack validate` prints
    expect(formatPackWide({ what: 'x', at: { file: 'src/a.ts', line: 3 } })).toBe('src/a.ts:3: x');
  });

  /**
   * The rule table in `docs/public-facing/cli.md` is what a pack author reads, and nothing derived it from these
   * keys — so it drifted both ways at once: it documented a `js-specifiers` pack rule that has never existed (the
   * relative `.js` form is `own-modules`') and left `source-resolution` out entirely.
   *
   * Compared as sets, not in order: the doc groups rules the way an author meets them, which is editorial, while
   * the order here is precedence. What must not differ is which rules exist, and which of them a pack may switch
   * off — which the table says per row rather than in a sentence counting the trailing ones, since that sentence
   * was right only for as long as nobody appended a switchable rule or flipped one, and nothing read it.
   */
  it('documents exactly the rules that exist, and which are switchable, in docs/public-facing/cli.md', () => {
    const doc = fs.readFileSync(path.join(REPO_ROOT, 'docs/public-facing/cli.md'), 'utf-8').split('\n');
    const header = doc.findIndex((line) => /^\|\s*Rule\s*\|/.test(line));
    expect(header, 'the rule table is gone from cli.md, or its header changed').toBeGreaterThan(-1);
    const after = doc.slice(header + 2);
    // `findIndex` answers -1 for a table that ends the file, and `slice(0, -1)` would drop its last row — a row
    // this would then report as missing, which is a confusing way to say "the table runs to the end"
    const ends = after.findIndex((line) => !line.startsWith('|'));
    const rows = ends === -1 ? after : after.slice(0, ends);
    // The marker is read from the end of the row rather than by splitting on `|`, so a pipe inside a rule's
    // description stays the author's business rather than this check's
    const documented = rows.flatMap((row) => {
      const key = /^\|\s*`([^`]+)`/.exec(row)?.[1];
      return key === undefined ? [] : [{ key, switchable: /\|\s*(yes|no)\s*\|\s*$/.exec(row)?.[1] }];
    });
    population('the rule table rows in cli.md', documented);
    expect(documented.map((row) => row.key).sort()).toEqual(PACK_RULES.map((rule) => rule.key).sort());

    // A row whose marker is missing or misspelled would otherwise read as "not switchable" and agree with the
    // table for every rule that is not, which is the half of this a set comparison alone cannot see
    expect(documented.filter((row) => row.switchable === undefined).map((row) => row.key),
      'these rows of the cli.md table say nothing in the Switchable? column').toEqual([]);
    expect(documented.filter((row) => row.switchable === 'yes').map((row) => row.key).sort(),
      'cli.md marks a different set of rules switchable than PACK_RULES declares, so a pack author is told they '
      + 'may allow a rule apack.json will refuse, or not told about one they may')
      .toEqual(PACK_RULES.filter((rule) => rule.switchable).map((rule) => rule.key).sort());
  });

  /**
   * The order in `PACK_RULES` *is* the precedence, so it is worth pinning: what stops the pack loading, then
   * what stops a specifier resolving, then what breaks on an app update, then the conventions.
   */
  it('declares that precedence in one place', () => {
    expect(PACK_RULES.map((rule) => rule.key)).toEqual([
      'source-resolution', 'contract-leaves',
      'host-imports', 'elmdb-imports',
      // cross-feature-imports is out of its cause group on purpose: its fix subsumes own-modules'
      'cross-feature-imports', 'own-modules', 'pack-own-aliases',
      'internal-package-imports',
      // component-sends sits beside untyped-sends: both answer "which send, from where"
      // window-storage sits beside backend-console: both say which API to reach for instead of a global
      'untyped-sends', 'component-sends', 'raw-transport', 'backend-console', 'window-storage',
      'repository-casts',
      // reserved-event-keys is last and contests nothing: no other rule reads a property name, so where it
      // sits is free, and a convention belongs after the rules about what a module imports
      'reserved-event-keys',
    ]);
  });
});

/**
 * The line the failure prints is the file the reader reads. They drifted once — the advice named a `"checks"`
 * key the reader never looks for — so this pastes it rather than matching its text.
 */
it('allowLineWorks: pasting the line the error prints switches the rule off', () => {
  const dir = pack({ 'apack.json': JSON.stringify({ id: 'example', name: 'Example', version: '1.0.0' }), 'package.json': JSON.stringify({ name: 'p', type: 'module' }), 'src/extensions/steps/x.ts': "console.log('x');\n" });
  const printed = (() => { try { refusePackRuleViolations(dir); return ''; } catch (err) { return (err as Error).message; } })();
  const advice = printed.split('\n').find((line) => line.includes('apack.json'));
  expect(advice).toBeDefined();
  const json = advice!.slice(advice!.indexOf('{'), advice!.lastIndexOf('}') + 1);
  const file = path.join(dir, 'apack.json');
  fs.writeFileSync(file, JSON.stringify({ ...JSON.parse(fs.readFileSync(file, 'utf8')), ...JSON.parse(json) }));
  expect(() => refusePackRuleViolations(dir)).not.toThrow();
});

/**
 * The one rule whose subject is not a file's text: what the pack's compiler resolves.
 *
 * The fixture installs a package shaped like `@apackdev/sdk` — an exports map with a source branch beside the
 * published one, `src/` and `dist/` both present — because that shape is the whole point: the branch is
 * unreachable for a real consumer and reachable for a linked checkout, and the rule is about which one this
 * pack's `tsc` picks.
 */
describe('source-resolution', () => {
  const withSdk = (tsconfig: Record<string, unknown>) => pack({
    'package.json': JSON.stringify({ name: 'p', type: 'module' }),
    'tsconfig.json': JSON.stringify({ compilerOptions: { module: 'esnext', moduleResolution: 'bundler', ...tsconfig } }),
    'node_modules/@apackdev/sdk/package.json': JSON.stringify({
      name: '@apackdev/sdk',
      exports: { '.': { '@apackdev/source': './src/index.ts', types: './dist/index.d.ts', default: './dist/index.js' } },
    }),
    'node_modules/@apackdev/sdk/src/index.ts': 'export const version = 1;\n',
    'node_modules/@apackdev/sdk/dist/index.d.ts': 'export declare const version: number;\n',
    'node_modules/@apackdev/sdk/dist/index.js': 'export const version = 1;\n',
    'src/system.ts': "import { version } from '@apackdev/sdk';\nexport const v = version;\n",
  });

  it('passes a pack that resolves the published dist', () => {
    expect(problems(withSdk({}), 'source-resolution')).toEqual([]);
  });

  it('refuses one whose tsconfig resolves a checkout\'s source, naming the file', () => {
    const found = problems(withSdk({ customConditions: ['@apackdev/source'] }), 'source-resolution');
    expect(found).toHaveLength(1);
    expect(found[0]).toContain('@apackdev/sdk -> node_modules/@apackdev/sdk/src/index.ts');
  });

  /** An `extends` chain is the route a rule that read the config text for `customConditions` would miss */
  it('refuses it through an extends chain too', () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'tsconfig.base.json'), JSON.stringify({ compilerOptions: { customConditions: ['@apackdev/source'] } }));
    fs.writeFileSync(path.join(dir, 'tsconfig.json'), JSON.stringify({
      extends: './tsconfig.base.json',
      compilerOptions: { module: 'esnext', moduleResolution: 'bundler' },
    }));
    expect(problems(dir, 'source-resolution')).toHaveLength(1);
  });

  /**
   * A config the rule cannot read is reported, not passed over. The opposite — `[]` for a pack nobody looked
   * at — is the shape `findMissingSourceConditions` refuses for the repo's own configs, with the reason that a
   * rule which guesses is a rule that lets the next one through.
   */
  it('reports a tsconfig that does not parse, rather than passing', () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'tsconfig.json'), '{ "compilerOptions": ');
    expect(problems(dir, 'source-resolution')).toEqual([expect.stringContaining('could not be read') as unknown as string]);
  });

  it('reports an extends naming a file that is not there', () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'tsconfig.json'), JSON.stringify({ extends: './tsconfig.missing.json' }));
    const found = problems(dir, 'source-resolution');
    expect(found).toHaveLength(1);
    expect(found[0]).toMatch(/could not be read.*tsconfig\.missing\.json/);
  });

  /** The one diagnostic that is about the file set and not resolution, so it must not make this rule fire */
  it('says nothing about a pack whose include matches no file', () => {
    const dir = pack({
      'package.json': JSON.stringify({ name: 'p', type: 'module' }),
      'tsconfig.json': JSON.stringify({ compilerOptions: { module: 'esnext', moduleResolution: 'bundler' }, include: ['src/**/*.ts'] }),
    });
    expect(problems(dir, 'source-resolution')).toEqual([]);
  });

  /**
   * The other route to source, and the one `tsc` cannot be asked about: nothing resolves a Vitest config's
   * `resolve.conditions` until the run, by which time the pack's suite has passed against workspace source.
   */
  it("reports a pack's vitest config naming the condition", () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'vitest.config.ts'),
      "export default { resolve: { conditions: ['@apackdev/source'] } };\n");
    expect(problems(dir, 'source-resolution')).toEqual(['vitest.config.ts:1: @apackdev/source']);
  });

  /** A pattern over the pack root, so a JS config is not a hole an external pack can fall into */
  it('reports a JS config too, not only a .ts one', () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'vitest.config.js'),
      "export default { resolve: { conditions: ['@apackdev/source'] } };\n");
    expect(problems(dir, 'source-resolution')).toEqual(['vitest.config.js:1: @apackdev/source']);
  });

  /** A string literal from the tree, not a text search, so a pack may still write about the condition */
  it('says nothing about a config that only mentions it in a comment', () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'vitest.config.ts'),
      '// A pack declares no @apackdev/source condition: it resolves the published dist\nexport default {};\n');
    expect(problems(dir, 'source-resolution')).toEqual([]);
  });

  it('says nothing about a package the pack does not have', () => {
    expect(problems(pack({ 'package.json': '{"name":"p"}', 'tsconfig.json': '{}', 'src/x.ts': 'export const x = 1;\n' }), 'source-resolution')).toEqual([]);
  });
});

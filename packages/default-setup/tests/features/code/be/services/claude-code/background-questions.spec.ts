import { createClaudeBackgroundQuestions } from '#features/code/be/services/claude-code/background-questions.ts'

const sessionId = '05ff1d31-597d-4537-8737-4407191add6e'
afterEach(() => vi.useRealTimers())
it('bounds overlapping reads and discards replies after the original owner closes', async () => {
  vi.useFakeTimers()
  let resolve!: (value: unknown) => void
  const request = vi.fn(() => new Promise<unknown>(done => { resolve = done }))
  const changed = vi.fn()
  const questions = createClaudeBackgroundQuestions({sessionId, transport: {request}, changed})
  await vi.advanceTimersByTimeAsync(4000)
  expect(request).toHaveBeenCalledTimes(1)
  questions.close()
  resolve({dialogs: []})
  await Promise.resolve()
  await vi.advanceTimersByTimeAsync(4000)
  expect(request).toHaveBeenCalledTimes(1)
  expect(questions.value).toBeUndefined()
  expect(changed).not.toHaveBeenCalled()
})
it('rejects foreign and malformed original dialog records without publishing them', async () => {
  vi.useFakeTimers()
  const request = vi.fn().mockResolvedValue({dialogs: [{sessionId: 'foreign'}]})
  const changed = vi.fn()
  const questions = createClaudeBackgroundQuestions({sessionId, transport: {request}, changed})
  await vi.advanceTimersByTimeAsync(1000)
  expect(questions.value).toBeUndefined()
  expect(changed).not.toHaveBeenCalled()
  questions.close()
})
it('discovers without a client, clears failed reads, and observes recovery and settlement', async () => {
  vi.useFakeTimers()
  const dialog = {id: 'dialog-1', revision: '24be904a-3c35-4981-9793-cbe7a6c19d46', sessionId, requestId: 'tool-1', toolName: 'AskUserQuestion', shownInput: {questions: []}, presentation: {previewFormat: null, extendedQuestions: false, optionalDescriptions: false, previews: []}}
  const request = vi.fn().mockResolvedValue({dialogs: [dialog]})
  const changed = vi.fn()
  const questions = createClaudeBackgroundQuestions({sessionId, transport: {request}, changed})
  await vi.advanceTimersByTimeAsync(0)
  expect(questions.value).toEqual(dialog)
  expect(changed).toHaveBeenCalledTimes(1)
  await vi.advanceTimersByTimeAsync(1000)
  expect(changed).toHaveBeenCalledTimes(1)
  request.mockRejectedValueOnce(new Error('worker unavailable'))
  await vi.advanceTimersByTimeAsync(1000)
  expect(questions.value).toBeUndefined()
  await vi.advanceTimersByTimeAsync(1000)
  expect(questions.value).toEqual(dialog)
  request.mockResolvedValue({dialogs: [{...dialog, sessionId: '24be904a-3c35-4981-9793-cbe7a6c19d46'}]})
  await vi.advanceTimersByTimeAsync(1000)
  expect(questions.value).toBeUndefined()
  request.mockResolvedValue({dialogs: [dialog]})
  await vi.advanceTimersByTimeAsync(1000)
  request.mockResolvedValue({dialogs: []})
  await vi.advanceTimersByTimeAsync(1000)
  expect(questions.value).toBeUndefined()
  questions.close()
})

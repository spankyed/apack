/** Recorded child program: executes in Node while the original CLI blocks on its editor. */
import {build} from 'esbuild'
import {readFile, writeFile} from 'node:fs/promises'
import {dirname, join, relative} from 'node:path'
import {fileURLToPath, pathToFileURL} from 'node:url'

const directory = join(dirname(fileURLToPath(import.meta.url)), '../src/features/code/be/services/claude-code/native-editor')
export const RECORDED_EDITOR_PROGRAM = join(directory, 'program.generated.ts')
export async function buildNativeEditorProgram(): Promise<string> {
  const result = await build({entryPoints: [join(directory, 'entry.ts')], bundle: true, write: false, format: 'esm', platform: 'node', target: 'node24', minify: false, legalComments: 'none', charset: 'utf8'})
  const output = result.outputFiles?.[0]
  if (!output) throw new Error('No output for the native editor child')
  return [
    '/** Generated by `npm run editor:update -w @app/default-setup`; do not edit. */',
    'export const CLAUDE_NATIVE_EDITOR_PROGRAM = [',
    ...output.text.trimEnd().split('\n').map(line => '  ' + JSON.stringify(line) + ','),
    "].join('\\n')", '',
  ].join('\n')
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const expected = await buildNativeEditorProgram(), recorded = await readFile(RECORDED_EDITOR_PROGRAM, 'utf8').catch(() => undefined)
  if (recorded === expected) console.log('native editor child is current')
  else if (process.argv.includes('--update')) {await writeFile(RECORDED_EDITOR_PROGRAM, expected); console.log('wrote ' + relative(process.cwd(), RECORDED_EDITOR_PROGRAM))}
  else {console.error('Run npm run editor:update -w @app/default-setup and commit the recorded program'); process.exitCode = 1}
}

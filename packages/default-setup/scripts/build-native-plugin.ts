/**
 * Build the Claude CLI plugin program, and hold the committed copy to it.
 *
 * The program under `native-plugin/` is the source; what the app writes into a CLI plugin directory is this
 * bundle. It is committed because the pack's backend has to carry it as *text* — it runs in the CLI's
 * runtime, not this one — and a derivation that is re-taken and compared on every run is what keeps the
 * committed copy honest:
 *
 *     npm run plugin:check  -w @app/default-setup   # re-bundle and compare
 *     npm run plugin:update -w @app/default-setup   # re-bundle and write
 *
 * Only `plugin:update` writes. What the chain runs is `native-plugin/program-built.spec.ts`, which compares
 * the same derivation in `test:unit:pack`, so a change to the program with a stale bundle beside it fails
 * there rather than at the next terminal launch.
 */
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pluginDir = join(here, '../src/features/code/be/services/claude-code/native-plugin');
const entry = join(pluginDir, 'entry.ts');
const recorded = join(pluginDir, 'program.generated.ts');

/**
 * One line of the program per line of the file.
 *
 * A single 10 KB string literal is not a diff anyone can read, and this file is regenerated by a command
 * whose output has to be reviewed before it is committed.
 */
function recordedModule(program: string): string {
  const lines = program.replace(/\n+$/, '').split('\n').map(line => '  ' + JSON.stringify(line) + ',');
  return [
    '/**',
    ' * The built Claude CLI plugin program — **generated**, by',
    ' * `npm run plugin:update -w @app/default-setup` (scripts/build-native-plugin.ts).',
    ' *',
    ' * Do not edit: the source is `native-plugin/entry.ts` and what it imports. The app writes this text',
    ' * into a temporary plugin directory with a `const APACK_NATIVE_CONFIG = {…}` line above it, which is',
    ' * the only thing that differs between runs.',
    ' */',
    'export const CLAUDE_NATIVE_PLUGIN_PROGRAM = [',
    ...lines,
    "].join('\\n');",
    '',
  ].join('\n');
}

async function bundled(): Promise<string> {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'esm',
    // The CLI's runtime, not Node's and not a browser's: nothing here touches either platform's globals.
    platform: 'neutral',
    target: 'es2022',
    // Unminified on purpose: a failure inside the plugin is reported by the CLI with a line number, and a
    // one-line program makes every one of them line 1.
    minify: false,
    legalComments: 'none',
    charset: 'utf8',
  });
  const output = result.outputFiles?.[0];
  if (!output) throw new Error('esbuild produced no output for ' + relative(process.cwd(), entry));
  return output.text;
}

/** Where the committed copy lives, for the spec that compares it. */
export const RECORDED_PLUGIN_PROGRAM = recorded;

/** The module the committed copy must equal: the bundle, as a file whose every line is one of the program's. */
export async function buildNativePluginProgram(): Promise<string> {
  return recordedModule(await bundled());
}

// The CLI half. A spec compares the same derivation, so importing this module must not run it.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();

async function main() {
  const program = await buildNativePluginProgram();
  const update = process.argv.includes('--update');
  const held = await readFile(recorded, 'utf8').catch(() => undefined);

  if (held === program) {
    console.log('plugin program is current');
  } else if (update) {
    await writeFile(recorded, program);
    console.log('wrote ' + relative(process.cwd(), recorded));
  } else {
    console.error(
      (held === undefined ? 'The built plugin program is missing' : 'The built plugin program is stale') +
        ': run `npm run plugin:update -w @app/default-setup` and commit ' +
        relative(process.cwd(), recorded),
    );
    process.exitCode = 1;
  }
}

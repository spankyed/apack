  await expect(appPage.locator('.command-suggestion-popup')).toBeHidden()
  const beforeReviewCount=await focused.locator('[data-native-agent-message]').count()
  await agentComposer.fill('NativeAgentSteerFixture:\u200b reply from the focused Agent composer.')

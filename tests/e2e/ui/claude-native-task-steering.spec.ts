  await expect(conversation.locator('[aria-label="Agent details"]')).toContainText('Model')
  await conversation.getByText('Agent prompt',{exact:true}).click()
  await expect(conversation.locator('details')).toContainText('Return the synthetic worker marker only.')
  await conversation.locator('details').scrollIntoViewIfNeeded()
  await appPage.screenshot({path:testInfo.outputPath('apack-native-task-details-running.png')})

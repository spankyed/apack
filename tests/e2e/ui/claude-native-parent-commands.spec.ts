import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { test, expect } from '@apackdev/testing'
const workspace = process.env.CLAUDE_RESEARCH_WORKSPACE, launcher = process.env.CLAUDE_RESEARCH_LAUNCHER, onboarding = process.env.CLAUDE_RESEARCH_ONBOARDING
test.skip(!workspace || !launcher || !onboarding, 'Explicit private native terminal fixture required')
test('runs native parent commands, panels and delayed lifecycle changes from the default composer', async ({ app, appPage }, testInfo) => {
  test.setTimeout(90000)
  expect(process.env.HOME).toBe(workspace)
  const { planScenario } = JSON.parse(await readFile(join(workspace!, 'question-preview-fixture.json'), 'utf8'))
  const restriction = planScenario === 'managed-clear'
  const { recognizeOnboardingPrompt } = await import(pathToFileURL(onboarding!).href)
  const errors: string[] = []; appPage.on('pageerror', error => errors.push(error.message))
  await app.waitForPlugin('default-setup/threads'); await app.navigate('default-setup/threads')
  await app.navigate('host/settings')
  await appPage.evaluate(() => { const settings = (window as any).applicationState.system.get('host/settings'); settings.send({ type: 'TAB.SELECT', tab: 'general' }); settings.send({ type: 'GENERAL_NAV.SELECT', item: 'secrets' }) })
  const provider = appPage.getByText('Claude Code CLI', { exact: true }).locator('..').locator('..').locator('..')
  await provider.getByPlaceholder('Path override (auto-detected if empty)').fill(launcher!)
  await appPage.waitForTimeout(700)
  await app.navigate('default-setup/threads')
  await appPage.evaluate(({ cwd, phase }) => { const actor = (window as any).applicationState.system.get('default-setup/threads'); actor.send({ type: 'NEW_THREAD_IN_PROJECT', directory: cwd }); actor.send({ type: 'VIEW_DASHBOARD' }); actor.send({ type: 'SET_MODE', mode: 'Claude Code' }); actor.send({ type: 'SET_PHASE', phase }) }, { cwd: workspace!, phase: 'Edit' })
  const card = appPage.locator('[data-onboarding-id="agent-chat-input"]')
  async function command(name: string, args = '') {
    const editor = card.locator('[contenteditable="true"]')
    await editor.fill(''); await editor.pressSequentially('/' + name)
    await appPage.locator('.command-suggestion-popup').getByText('/' + name, { exact: true }).click()
    if (args) await editor.pressSequentially(args)
    await card.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(editor).toHaveText('')
  }
  await command('cc-set-dir', workspace!)
  await card.locator('[contenteditable="true"]').fill('Seed this private native interface session.')
  await card.getByRole('button', { name: 'Send', exact: true }).click()
  const context = () => appPage.evaluate(() => { const state = (window as any).applicationState.system.get('default-setup/threads').getSnapshot().context; return { threadId: state.currentThread?.id, topic: state.currentThread?.topic, phase: state.phase, sessionId: state.currentThread?.context?.claudeCode?.sessionId, turns: state.currentThread?.context?.claudeCode?.turns, claude: state.currentThread?.context?.claudeCode, messages: state.currentThread?.messages, native: Object.values(state.nativeTerminalViews).find((view: any) => view.threadId === state.currentThread?.id) } as any })
  await expect.poll(async () => (await context()).turns).toBe(1)
  const sessionId = (await context()).sessionId; expect(sessionId).toBeTruthy()
  const section = appPage.getByRole('region', { name: 'Claude native interface', exact: true })
  await expect(section.getByRole('button', { name: 'Use native interface', exact: true })).toBeEnabled()
  await section.getByRole('button', { name: 'Use native interface', exact: true }).click()
  const input = section.locator('textarea.xterm-helper-textarea')
  let theme = false, security = false, navigated = false, trusted = false
  await expect.poll(async () => {
    const current = await context(), native = current.native
    const text = native?.output?.map((chunk: any) => chunk.text).join('') ?? ''
    const screen = recognizeOnboardingPrompt(text, workspace)
    if (screen === 'theme' && !theme) { theme = true; await input.press('Enter') }
    else if (screen === 'security-notes' && theme && !security) { security = true; await input.press('Enter') }
    else if (screen === 'workspace-trust' && !navigated) { navigated = true; await input.press('ArrowDown') }
    else if (screen === 'workspace-trust-selected' && navigated && !trusted) { trusted = true; await input.press('Enter') }
    return native?.state?.status === 'live' && (restriction ? native.state.mainStatus === undefined : native.state.mainStatus?.includes('AppNativeMain ' + sessionId))
  }, { timeout: 25000, intervals: [250] }).toBe(true)
  await expect(card).toBeHidden()
  const boundNativePid = (await context()).native.state.nativePid
  await section.getByRole('button', {name:'Back to conversation',exact:true}).click()
  await appPage.locator('.cursor-row-resize').click({button:'right'})
  const composer=card.locator('[contenteditable="true"]')
  const submission = () => appPage.evaluate(() => {
    const c = (window as any).applicationState.system.get('default-setup/threads').getSnapshot().context
    return Object.values(c.nativeTerminalViews).map((v: any) => v.submission).filter(Boolean).sort((a: any, b: any) => b.revision - a.revision)[0] as any
  })
  await appPage.setViewportSize({ width: 680, height: 600 })
  async function sendNative(text: string) { const before = (await submission())?.revision ?? 0; await composer.fill(text); await expect(composer).toHaveText(text); await card.getByRole('button', { name: 'Send', exact: true }).click(); await expect.poll(async () => (await submission())?.revision ?? 0).toBeGreaterThan(before) }
  const structuredDraft = '**Native structured title**\n\n- first\n- second'
  await composer.fill('NativeStructureFixture')
  await expect(composer.locator('strong')).toHaveText('Native structured title')
  await expect(composer.locator('li')).toHaveText(['first', 'second'])
  await expect(composer.locator('.claude-prompt-decoration')).toHaveText(['first', 'second'])
  await expect(composer.locator('.claude-prompt-decoration').first()).toHaveCSS('color', 'rgb(255, 170, 0)')
  await expect(composer.locator('.claude-prompt-decoration').last()).toHaveCSS('text-decoration-line', 'underline')
  await card.getByRole('button', { name: 'Session tools', exact: true }).click()
  await card.getByRole('button', { name: 'Read structured draft', exact: true }).click()
  await expect.poll(async () => { try { return JSON.parse(await readFile(join(workspace!, 'native-structure-read.json'), 'utf8')) } catch { return undefined } }).toMatchObject({ text: structuredDraft, cursor: structuredDraft.length })
  await appPage.screenshot({ path: testInfo.outputPath('apack-native-structural-prompt.png') })
  await card.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(composer).toHaveText('')
  await expect.poll(async () => (await submission())?.receipt?.text).toBe(structuredDraft)
  const structureEvents = JSON.parse(await readFile(join(workspace!, 'native-main-prompt-edits.json'), 'utf8'))
  expect(structureEvents.some((event: any) => event.result?.text === '**Native structured title**\n\n*   first\n*   second' && event.result.decorations?.length === 2)).toBe(true)
  await sendNative('Populate the native conversation before parent command verification.')
  await expect(composer).toHaveText('')
  await expect.poll(async () => (await context()).native.state.lastTurn?.reason, { timeout: 20000 }).toBe('answer')
  await expect.poll(async () => (await context()).native.state.busy, { timeout: 20000 }).toBe(false)
  await expect.poll(async () => (await context()).claude.chatState).toBe('success')
  await sendNative('/context')
  await appPage.waitForTimeout(300)
  await writeFile(join(workspace!, 'native-main-command-debug.json'), JSON.stringify(await appPage.evaluate(() => { const c = (window as any).applicationState.system.get('default-setup/threads').getSnapshot().context; return { mode: c.mode, threadId: c.currentThread?.id, terminals: Object.entries(c.nativeTerminalViews).map(([id, v]: any) => ({ id, threadId: v.threadId, submission: v.submission, state: { status: v.state?.status, ownerId: v.state?.ownerId, sessionId: v.state?.sessionId, view: v.state?.view }, problem: v.problem })), mounts: Object.entries(c.nativeUiViews).map(([id, v]: any) => ({ id, state: v.state, prompt: v.prompt })) } }), null, 2))
  await appPage.screenshot({ path: testInfo.outputPath('native-main-command-debug.png') })
  // Exercise normal command delivery; invisible-paste prompt settlement is a separate finding.
  await expect(composer).toHaveText('')
  await expect.poll(async () => (await submission())?.command?.kind).toBe('command_output')
  const output = appPage.getByRole('region', { name: 'Native command output', exact: true })
  await expect(output).toContainText('Native command result: context')
  await expect(composer).toHaveText('')
  await output.getByRole('button', { name: 'Expand output', exact: true }).click()
  await expect(card).toBeHidden()
  const reading = output.getByRole('region', { name: 'Command result', exact: true })
  await expect(reading).toBeVisible()
  expect((await reading.boundingBox())!.height).toBeGreaterThan(200)
  await reading.focus(); await reading.press('End')
  await appPage.screenshot({ path: testInfo.outputPath('apack-main-context-expanded.png') })
  await output.getByRole('button', { name: 'Show composer', exact: true }).click()
  await expect(card).toBeVisible()
  await composer.fill('Keep my main draft while reading command output')
  const sendBox = await card.getByRole('button', { name: 'Send', exact: true }).boundingBox()
  expect(sendBox!.y).toBeGreaterThanOrEqual(0); expect(sendBox!.y + sendBox!.height).toBeLessThanOrEqual(600)
  await appPage.screenshot({ path: testInfo.outputPath('apack-main-context-with-composer.png') })
  const nativeResult = appPage.locator('[data-native-command-output]').filter({ has: appPage.getByRole('button', { name: 'Inspect native command result', exact: true }) }).last()
  await expect(nativeResult).toContainText('Native command result: context')
  await composer.fill('Keep command result inspection draft')
  await nativeResult.getByRole('button', { name: 'Inspect native command result', exact: true }).click()
  await expect.poll(async () => { try { return JSON.parse(await readFile(join(workspace!, 'native-command-output-hook.json'), 'utf8')).props?.command } catch { return undefined } }).toBe('context')
  const hook = JSON.parse(await readFile(join(workspace!, 'native-command-output-hook.json'), 'utf8'))
  expect(hook.requestId).toBe(await nativeResult.getAttribute('data-native-command-output'))
  expect(hook.props).toMatchObject({ command: 'context', args: '', isErrored: false })
  expect(hook.props.text).toContain('Context Usage')
  expect(hook.box.text).toBe('Keep command result inspection draft')
  expect((await submission()).command.text).toContain('Context Usage')
  await expect(composer).toHaveText('Keep command result inspection draft')
  await appPage.screenshot({ path: testInfo.outputPath('apack-native-command-output.png') })
  await output.getByRole('button', { name: 'Back to messages', exact: true }).click()
  await expect(composer).toBeFocused()
  await expect(composer).toHaveText('Keep command result inspection draft')
  await sendNative('/help')
  const help = appPage.getByRole('dialog', { name: 'Native /help panel', exact: true })
  await expect(help).toBeVisible(); await expect(card).toBeHidden()
  await help.getByRole('button', { name: 'Close panel', exact: true }).click()
  await expect(help).toBeHidden(); await expect(composer).toBeFocused()
  await sendNative('/cost')
  const usage = appPage.getByRole('dialog', { name: 'Native /usage panel', exact: true })
  await expect(usage).toBeVisible()
  await usage.locator('textarea.xterm-helper-textarea').press('ArrowLeft')
  await appPage.screenshot({ path: testInfo.outputPath('apack-main-native-settings-compact.png') })
  await usage.locator('textarea.xterm-helper-textarea').press('Escape')
  await expect(usage).toBeHidden(); await expect(composer).toBeFocused()
  await writeFile(join(workspace!, 'native-parent-delay-request'), 'ready')
  await expect.poll(async () => { try { return await readFile(join(workspace!, 'native-parent-delay-ready'), 'utf8') } catch { return '' } }).toBe('ready')
  const compactStarted = Date.now()
  await sendNative('/compact')
  await expect(card.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  await expect.poll(async () => (await submission())?.status, { timeout: 20000 }).toBe('accepted')
  const compact = (await submission()).command
  expect(compact.kind).toBe('command_complete'); expect(compact.commandName).toBe('compact'); expect(compact.boundaryId).toBeTruthy()
  expect(Date.now() - compactStarted).toBeGreaterThanOrEqual(6000)
  await expect(composer).toHaveText('')
  expect((await context()).sessionId).toBe(sessionId)
  const commandHistory = () => appPage.evaluate(() => { const c = (window as any).applicationState.system.get('default-setup/threads').getSnapshot().context; return (c.currentThread?.messages ?? []).filter((m: any) => m.context?.claudeNativeCommand).map((m: any) => ({ sender: m.sender, text: m.text, uuid: m.context.cliUuid, command: m.context.claudeNativeCommand, human: m.context.claudeNativeUserMessage })) })
  await expect.poll(async () => (await commandHistory()).find((m: any) => m.uuid === compact.messageId)).toMatchObject({ sender: 'user', text: '/compact', command: { kind: 'invocation' } })
  await expect.poll(async () => (await commandHistory()).some((m: any) => m.sender === 'assistant' && m.command.kind === 'output' && m.text.startsWith('Compacted'))).toBe(true)
  expect((await commandHistory()).every((m: any) => !m.human && !/<(?:command-name|command-message|command-args|local-command-stdout)>|\u001b/.test(m.text))).toBe(true)
  await expect(appPage.locator('[data-testid="chat-transcript"]')).not.toContainText('<command-name>')
  await expect(appPage.locator('[data-testid="chat-transcript"]')).not.toContainText('<local-command-stdout>')
  await appPage.screenshot({ path: testInfo.outputPath('apack-main-compact-completed.png') })
  await sendNative('/clear')
  await expect.poll(async () => (await submission())?.command?.commandName).toBe('clear')
  const clear = (await submission()).command
  expect(clear.kind).toBe('command_complete'); expect(clear.sessionId).not.toBe(sessionId)
  await expect.poll(async () => (await context()).sessionId).toBe(clear.sessionId)
  await expect(composer).toHaveText('')
  expect((await context()).native.state.nativePid).toBe(boundNativePid)
  await sendNative('Ordinary main input after native clear')
  await expect(composer).toHaveText('')
  await expect.poll(async () => (await submission())?.receipt?.sessionId).toBe(clear.sessionId)
  const postClearReceipt = (await submission()).receipt
  await expect.poll(async () => (await context()).claude.chatState).toBe('success')
  const promptHooks = JSON.parse(await readFile(join(workspace!, 'native-parent-prompt-hooks.json'), 'utf8'))
  expect(promptHooks.some((row: any) => row.text === 'Ordinary main input after native clear')).toBe(true)
  const observed = JSON.parse(await readFile(join(workspace!, 'native-command-lifecycle.json'), 'utf8'))
  expect(observed.find((row: any) => row.command === 'compact').boundaries.some((row: any) => row.uuid === compact.boundaryId)).toBe(true)
  const clearRun = observed.find((row: any) => row.command === 'clear')
  expect(clearRun.sessionIdAfter).toBe(clear.sessionId)
  expect(clearRun.queryEvents.some((event: any) => event.newConversationId === clear.conversationId)).toBe(true)
  await appPage.screenshot({ path: testInfo.outputPath('apack-main-clear-continued.png') })
  await section.getByRole('button', { name: 'Use native interface', exact: true }).click()
  await section.getByRole('button', { name: 'Stop session', exact: true }).click()
  await expect.poll(async () => (await context()).native?.state.status ?? 'exited').toMatch(/^(exited|error)$/)
  const back = section.getByRole('button', { name: 'Back to conversation', exact: true }); if (await back.isVisible()) await back.click()
  await composer.fill('Continue the new saved session after native parent commands.')
  await card.getByRole('button', { name: 'Send', exact: true }).click()
  await expect.poll(async () => (await context()).claude.chatState).toBe('success')
  expect((await context()).sessionId).toBe(clear.sessionId); expect(errors).toEqual([])
  await writeFile(join(workspace!, 'native-terminal-app-evidence.json'), JSON.stringify({ actualAppGui: true, nativePlanScenario: planScenario, nativeParentText: true, nativeParentPanels: true, nativeParentDelayedCompact: true, nativeParentClear: true, nativeParentPostClearReceipt: true, nativeParentDraftPreserved: true, nativeCommandHistory: true, nativePromptStructure: true, nativePromptDecorations: true, nativeCommandOutput: true, resumedPrintSameSession: true, sameNativeOwner: true, sessionId, finalSessionId: clear.sessionId, boundNativePid, compact, clear, postClearReceipt, browserErrors: errors }, null, 2))
})
